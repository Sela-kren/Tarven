"""
The reference heroines as numbers: one module per ref (generated by tools/refkit/make_specs.py) and the MEDIAN
target built from all of them. This is what the heroine is built towards and checked against (ref_check.py).

    import ref_specs as R
    R.MEDIAN["sizes"]["waist_girth"]        # 0.376 of stature
    R.RANGE["sizes"]["waist_girth"]         # (min, max) over the refs that vote on it
    R.at(R.MEDIAN["sizes"]["waist_girth"])  # in metres at her stature
    R.REFS["luna_snow"].SIZES               # one ref

Only measurements are stored: no ref mesh, texture or UV. Medians use only the refs that may vote on a value
(SKIP in each module: clothes over that part). Plain Python, no numpy, no Blender.
"""
import importlib, statistics

from ._refs import MODULES

REFS = {m: importlib.import_module(f"{__name__}.{m}") for m in MODULES}
STATURE = 1.70        # her barefoot stature in metres


def at(share, stature=STATURE):
    return None if share is None else share * stature


def _pool(section, k):
    out = []
    for r in REFS.values():
        if k in r.SKIP:
            continue
        v = getattr(r, section.upper()).get(k)
        if v is not None:
            out.append(v)
    return out


def _scalars(section):
    keys = []
    for r in REFS.values():
        for k in getattr(r, section.upper()):
            if k not in keys:
                keys.append(k)
    med, rng, n = {}, {}, {}
    for k in keys:
        p = _pool(section, k)
        if p:
            med[k], rng[k], n[k] = round(statistics.median(p), 4), (min(p), max(p)), len(p)
    return med, rng, n


def _joints():
    names = [k for k in next(iter(REFS.values())).JOINTS if k != "arm_angle_deg"]
    med, rng = {}, {}
    for k in names:
        vals = [r.JOINTS[k] for r in REFS.values() if r.JOINTS.get(k)]
        med[k] = tuple(round(statistics.median(v[i] for v in vals), 4) for i in range(3))
        rng[k] = tuple((min(v[i] for v in vals), max(v[i] for v in vals)) for i in range(3))
    return med, rng


def _profile():
    """Median silhouette by height from the refs tight there, lightly smoothed (5 rows)."""
    rows = {}
    for r in REFS.values():
        if not r.PROFILE_BAND:
            continue
        lo, hi = r.PROFILE_BAND
        for g, f, b, h in r.PROFILE:
            if lo <= g <= hi:
                rows.setdefault(g, []).append((f, b, h))
    grid = sorted(rows)
    raw = [[statistics.median(v[i] for v in rows[g]) for i in range(3)] for g in grid]
    rng = [[(min(v[i] for v in rows[g]), max(v[i] for v in rows[g])) for i in range(3)] for g in grid]
    out = []
    for j, g in enumerate(grid):
        win = raw[max(0, j - 2):j + 3]
        out.append((g, *(round(sum(w[i] for w in win) / len(win), 4) for i in range(3))))
    return out, rng


def _head():
    hs = [r for r in REFS.values() if r.HEAD]
    if not hs:
        return None, None, None, None
    fr = {k: round(statistics.median(r.HEAD[k] for r in hs if k in r.HEAD), 4) for k in hs[0].HEAD}
    face, face_rng = {}, {}
    for k in hs[0].FACE:
        vals = [r.FACE[k] for r in hs if k in r.FACE]
        if not isinstance(vals[0], tuple):
            continue
        cols = []
        rc = []
        for i in range(3):
            c = [v[i] for v in vals if v[i] is not None]
            cols.append(round(statistics.median(c), 4) if c else None)
            rc.append((min(c), max(c)) if c else None)
        face[k], face_rng[k] = tuple(cols), tuple(rc)
    tabs = {}
    for k in hs[0].HEAD_TABLES:
        n = len(hs[0].HEAD_TABLES[k])
        col = []
        for i in range(n):
            c = [r.HEAD_TABLES[k][i] for r in hs if r.HEAD_TABLES[k][i] is not None]
            col.append(round(statistics.median(c), 4) if c else None)
        tabs[k] = col
    return fr, face, face_rng, tabs


_h, _hr, N_HEIGHTS = _scalars("heights")
_s, _sr, N_SIZES = _scalars("sizes")
_j, _jr = _joints()
_p, _pr = _profile()
_hf, _ff, _ffr, _ht = _head()

MEDIAN = {"heights": _h, "sizes": _s, "joints": _j, "profile": _p,
          "head": _hf, "face": _ff, "head_tables": _ht}
RANGE = {"heights": _hr, "sizes": _sr, "joints": _jr, "profile": _pr, "face": _ffr,
         "head": {k: (min(r.HEAD[k] for r in REFS.values() if r.HEAD and k in r.HEAD),
                      max(r.HEAD[k] for r in REFS.values() if r.HEAD and k in r.HEAD)) for k in (_hf or {})}}
